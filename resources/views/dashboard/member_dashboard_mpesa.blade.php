    Payment Description Tips
  </div>
  <div class="card-body">
    <h5 class="card-title">How Your Payment Will Be Classified</h5>
    <p class="card-text">
      The system automatically categorizes payments based on keywords in your payment description.
    </p>
    <ul>
      <li><strong>“Share”, “Shares”, “Deposit”, “Deposits”</strong> → Treated as <strong>Share Deposits</strong></li>
      <li><strong>“Capital”</strong> → Treated as <strong>Capital Contribution</strong></li>
      <li><strong>Others</strong> → Credited to <strong>FOSA Savings</strong></li>
    </ul>
    <p>
      If no keyword is provided, the system will classify the payment based on your past transactions.
    </p>
  </div>
</div>

